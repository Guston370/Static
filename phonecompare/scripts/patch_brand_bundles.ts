function patchFile(add: ModelAddition) {
  const filePath = path.resolve(__dirname, 'mobile_data', add.brandFile);
  let content = fs.readFileSync(filePath, 'utf8');

  // Check if already patched
  if (content.includes(add.modelCode.split('\n')[1].trim())) {
    console.log(`Skipping ${add.brandFile}: already patched.`);
    return;
  }

  // Find models array end: "];\n\nconst variants" or "];\nconst variants"
  const variantsMarkerIndex = content.indexOf('const variants: MobileVariant[] = [');
  if (variantsMarkerIndex === -1) {
    throw new Error(`Could not find variants marker in ${add.brandFile}`);
  }
  const lastBracketBeforeVariants = content.lastIndexOf('];', variantsMarkerIndex);
  if (lastBracketBeforeVariants === -1) {
    throw new Error(`Could not find models array end bracket in ${add.brandFile}`);
  }

  content =
    content.slice(0, lastBracketBeforeVariants) +
    '\n' +
    add.modelCode +
    '\n' +
    content.slice(lastBracketBeforeVariants);

  // Re-find variants and images markers after content modification
  const newVariantsMarkerIndex = content.indexOf('const variants: MobileVariant[] = [');
  const imagesMarkerIndex = content.indexOf('const images: MobileImageCatalogEntry[] = [');
  if (imagesMarkerIndex === -1) {
    throw new Error(`Could not find images marker in ${add.brandFile}`);
  }
  const lastBracketBeforeImages = content.lastIndexOf('];', imagesMarkerIndex);

  const variantChunk = add.variantCodes.join('\n');
  content =
    content.slice(0, lastBracketBeforeImages) +
    '\n' +
    variantChunk +
    '\n' +
    content.slice(lastBracketBeforeImages);

  // Now find images array end: "];\n\nexport const" or "];\nexport const"
  const bundleExportIndex = content.indexOf('export const ');
  if (bundleExportIndex === -1) {
    throw new Error(`Could not find bundle export in ${add.brandFile}`);
  }
  const lastBracketBeforeExport = content.lastIndexOf('];', bundleExportIndex);

  content =
    content.slice(0, lastBracketBeforeExport) +
    '\n' +
    add.imageCode +
    '\n' +
    content.slice(lastBracketBeforeExport);

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`✓ Successfully patched ${add.brandFile}`);
}

for (const add of additions) {
  patchFile(add);
}
