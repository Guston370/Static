export function discoverModels() {
  const rawPath = path.join(__dirname, '..', 'data', 'raw', 'models_inventory.json');
  const normalizedPath = path.join(__dirname, '..', 'data', 'normalized', 'models_catalog.json');

  fs.writeFileSync(rawPath, JSON.stringify(INDIAN_ACTIVE_MODELS, null, 2), 'utf8');
  fs.writeFileSync(normalizedPath, JSON.stringify(INDIAN_ACTIVE_MODELS, null, 2), 'utf8');

  const brandCount = new Set(INDIAN_ACTIVE_MODELS.map((m) => m.brandSlug)).size;
  const activeCount = INDIAN_ACTIVE_MODELS.filter((m) => m.status === 'ACTIVE').length;
  const upcomingCount = INDIAN_ACTIVE_MODELS.filter((m) => m.status === 'UPCOMING').length;

  console.log(`Discovered ${INDIAN_ACTIVE_MODELS.length} total models across ${brandCount} brands.`);
  console.log(`- Currently Active: ${activeCount}`);
  console.log(`- Upcoming / Announced: ${upcomingCount}`);
  console.log(`Saved raw inventory to ${rawPath}`);
  console.log(`Saved normalized catalog to ${normalizedPath}`);
}

if (require.main === module) {
  discoverModels();
}
